import { Router } from 'express';
import { protect } from '../middleware/auth.js';
import { authorize } from '../middleware/role.js';
import validate from '../middleware/validate.js';
import asyncHandler from '../utils/asyncHandler.js';
import * as c from '../controllers/finance.js';
import * as v from '../validators/finance.js';
import { detail, history, list } from '../validators/hms.js';
const router = Router();
const manage = authorize('admin', 'manager');
const desk = authorize('admin', 'manager', 'receptionist');
const guestOrDesk = authorize('admin', 'manager', 'receptionist', 'user');
router.use(protect);
router.get('/services', validate(list), asyncHandler(c.listServices));
router.post('/services', manage, validate(v.serviceCreate), asyncHandler(c.saveService));
router.put('/services/:id', manage, validate(v.serviceEdit), asyncHandler(c.saveService));
router.get('/service-assignees', desk, validate(list), asyncHandler(c.serviceAssignees));
router.get('/service-requests', validate(v.requestList), asyncHandler(c.listRequests));
router.post('/service-requests', guestOrDesk, validate(v.serviceRequest), asyncHandler(c.createRequest));
router.put('/service-requests/:id/assignment', desk, validate(v.assignRequest), asyncHandler(c.assignRequest));
router.post('/service-requests/:id/action', validate(v.requestAction), asyncHandler(c.actRequest));
router.get('/service-requests/:id/history', validate(history), asyncHandler(c.requestHistory));
router.get('/stays/:id/bill', guestOrDesk, validate(detail), asyncHandler(c.getBill));
router.put('/stays/:id/bill', manage, validate(v.billConfig), asyncHandler(c.configureBill));
router.post('/stays/:id/charges', desk, validate(v.charge), asyncHandler(c.addCharge));
router.post('/stays/:id/charges/:chargeId/void', manage, validate(v.voidCharge), asyncHandler(c.voidCharge));
router.post('/stays/:id/payments', desk, validate(v.payment), asyncHandler(c.addPayment));
router.post('/stays/:id/invoice/email', guestOrDesk, validate(v.emailInvoice), asyncHandler(c.emailInvoice));
router.get('/stays/:id/billing-history', guestOrDesk, validate(history), asyncHandler(c.billingHistory));
router.get('/feedback', authorize('admin', 'manager', 'user'), validate(v.feedbackList), asyncHandler(c.listFeedback));
router.post('/feedback', authorize('user'), validate(v.feedback), asyncHandler(c.createFeedback));
export default router;
