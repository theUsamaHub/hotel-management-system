import { Router } from 'express';
import { protect } from '../middleware/auth.js';
import { authorize } from '../middleware/role.js';
import validate from '../middleware/validate.js';
import asyncHandler from '../utils/asyncHandler.js';
import * as c from '../controllers/hms.js';
import * as v from '../validators/hms.js';
const router = Router();
const manage = authorize('admin', 'manager');
const desk = authorize('admin', 'manager', 'receptionist');
const book = authorize('admin', 'manager', 'receptionist', 'user');
const staff = authorize('admin', 'manager', 'receptionist', 'housekeeping', 'maintenance');
router.use(protect);
router.get('/hotels', validate(v.catalog), asyncHandler(c.catalog));
router.get('/room-types', validate(v.list), asyncHandler(c.listTypes));
router.post('/room-types', manage, validate(v.typeCreate), asyncHandler(c.saveType));
router.put('/room-types/:id', manage, validate(v.typeUpdate), asyncHandler(c.saveType));
router.get('/rooms', staff, validate(v.list), asyncHandler(c.listRooms));
router.post('/rooms', manage, validate(v.roomCreate), asyncHandler(c.saveRoom));
router.put('/rooms/:id', manage, validate(v.roomUpdate), asyncHandler(c.saveRoom));
router.patch('/rooms/:id/status', authorize('admin', 'manager', 'housekeeping', 'maintenance'), validate(v.roomStatus), asyncHandler(c.changeRoomStatus));
router.get('/rooms/:id/history', staff, validate(v.history), asyncHandler(c.roomHistory));
router.get('/guests', book, validate(v.list), asyncHandler(c.listGuests));
router.post('/guests', book, validate(v.guestCreate), asyncHandler(c.saveGuest));
router.put('/guests/:id', book, validate(v.guestUpdate), asyncHandler(c.saveGuest));
router.get('/availability', book, validate(v.availability), asyncHandler(c.availability));
router.get('/reservations', book, validate(v.bookingList), asyncHandler(c.listBookings));
router.post('/reservations', book, validate(v.bookingCreate), asyncHandler(c.createBooking));
router.get('/reservations/:id', book, validate(v.detail), asyncHandler(c.getBooking));
router.get('/reservations/:id/history', book, validate(v.history), asyncHandler(c.bookingHistory));
router.put('/reservations/:id', book, validate(v.bookingUpdate), asyncHandler(c.updateBooking));
router.post('/reservations/:id/confirm', desk, validate(v.bookingAction), (req, _res, next) => { req.params.action = 'confirm'; next(); }, asyncHandler(c.updateBooking));
router.post('/reservations/:id/cancel', book, validate(v.bookingAction), (req, _res, next) => { req.params.action = 'cancel'; next(); }, asyncHandler(c.updateBooking));
export default router;
