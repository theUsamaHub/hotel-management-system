import { Router } from 'express';
import { protect } from '../middleware/auth.js';
import { authorize } from '../middleware/role.js';
import validate from '../middleware/validate.js';
import asyncHandler from '../utils/asyncHandler.js';
import * as c from '../controllers/operations.js';
import * as v from '../validators/operations.js';
import { detail, history, list } from '../validators/hms.js';
const router = Router();
const managers = authorize('admin', 'manager');
const desk = authorize('admin', 'manager', 'receptionist');
const guests = authorize('admin', 'manager', 'receptionist', 'user');
const cleaners = authorize('admin', 'manager', 'receptionist', 'housekeeping');
router.use(protect);
router.get('/assignees', desk, validate(v.assignees), asyncHandler(c.assignees));
router.post('/reservations/:id/check-in', desk, validate(v.checkIn), asyncHandler(c.checkIn));
router.get('/stays', guests, validate(v.stayList), asyncHandler(c.listStays));
router.get('/stays/:id', guests, validate(detail), asyncHandler(c.stayDetail));
router.get('/stays/:id/history', guests, validate(history), asyncHandler(c.stayHistory));
router.post('/stays/:id/keys', desk, validate(v.issueKey), asyncHandler(c.issueKey));
router.post('/stays/:id/keys/:keyId/close', desk, validate(v.closeKey), asyncHandler(c.closeKey));
router.post('/stays/:id/check-out', desk, validate(v.checkout), asyncHandler(c.checkout));
router.get('/housekeeping/queue', cleaners, validate(list), asyncHandler(c.housekeepingQueue));
router.get('/housekeeping', cleaners, validate(v.housekeepingList), asyncHandler(c.listHousekeeping));
router.post('/housekeeping', desk, validate(v.housekeepingCreate), asyncHandler(c.createHousekeeping));
router.put('/housekeeping/:id', desk, validate(v.housekeepingEdit), asyncHandler(c.editHousekeeping));
router.post('/housekeeping/:id/action', authorize('admin', 'manager', 'housekeeping'), validate(v.taskAction), asyncHandler(c.actHousekeeping));
router.get('/housekeeping/:id/history', cleaners, validate(history), asyncHandler(c.housekeepingHistory));
router.get('/maintenance', validate(v.maintenanceList), asyncHandler(c.listMaintenance));
router.post('/maintenance', validate(v.maintenanceCreate), asyncHandler(c.createMaintenance));
router.put('/maintenance/:id', managers, validate(v.maintenanceEdit), asyncHandler(c.editMaintenance));
router.post('/maintenance/:id/action', authorize('admin', 'manager', 'maintenance'), validate(v.maintenanceAction), asyncHandler(c.actMaintenance));
router.get('/maintenance/:id/history', validate(history), asyncHandler(c.maintenanceHistory));
router.get('/maintenance/:id/affected', desk, validate(history), asyncHandler(c.affectedBookings));
export default router;
