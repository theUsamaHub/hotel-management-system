import { Router } from 'express';
import authRoutes from './auth.js';
import userRoutes from './user.js';
import categoryRoutes from './category.js';
import mediaRoutes from './media.js';
import accountRoutes from './account.js';
import hotelRoutes from './hotel.js';
import staffRoutes from './staff.js';
import hmsRoutes from './hms.js';
import { protect } from '../middleware/auth.js';
import { authorize } from '../middleware/role.js';
import validate from '../middleware/validate.js';
import asyncHandler from '../utils/asyncHandler.js';
import { listAudit } from '../controllers/account.js';
import { auditSchema } from '../validators/account.js';

const router = Router();
router.use('/auth', authRoutes);
router.use('/account', accountRoutes);
router.get('/audit', protect, authorize('admin'), validate(auditSchema), asyncHandler(listAudit));
router.use('/users', userRoutes);
router.use('/hotels', hotelRoutes);
router.use('/staff', staffRoutes);
router.use('/hms', hmsRoutes);
router.use('/categories', categoryRoutes);
router.use('/media', mediaRoutes);
router.get('/health', (_req, res) => res.json({ success: true, message: 'API is healthy' }));
export default router;
